#!/usr/bin/env node
// Static build for Vercel (no bundler, no runtime dependencies):
//   1. copies app/ to dist/
//   2. writes dist/config.js from PUBLIC environment variables only
//   3. refuses to build with a secret / service-role key
//   4. verifies the Content-Security-Policy hash of the print-paginator script
//
// Environment (set in Vercel → Project → Settings → Environment Variables):
//   SUPABASE_URL                 https://<project-ref>.supabase.co          (required in production)
//   SUPABASE_PUBLISHABLE_KEY     sb_publishable_… or legacy anon JWT        (required in production)
//   DSP_RECOVERY_CACHE           off | session | local   (default session)
//   DSP_IDLE_SIGNOUT_MINUTES     default 120, 0 disables
//   DSP_EDIT_IDLE_RELEASE_MINUTES default 20
import { cpSync, rmSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { paginatorScript, sha256 } from './csp.mjs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'app'), out = join(root, process.env.DSP_OUT_DIR || 'dist');
const env = process.env;
const appEnv = env.VERCEL_ENV || env.DSP_APP_ENV || 'development';
const fail = (m) => { console.error(`\n✖ build failed: ${m}\n`); process.exit(1); };

// ---- configuration ---------------------------------------------------------
const url = (env.SUPABASE_URL || env.NEXT_PUBLIC_SUPABASE_URL || '').trim();
const key = (env.SUPABASE_PUBLISHABLE_KEY || env.SUPABASE_ANON_KEY || env.NEXT_PUBLIC_SUPABASE_ANON_KEY || '').trim();

if (key) {
  if (/^sb_secret_/i.test(key)) fail('SUPABASE_PUBLISHABLE_KEY is a SECRET key (sb_secret_…). Use the publishable key.');
  const parts = key.split('.');
  if (parts.length === 3) {
    try {
      const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
      if (payload.role && payload.role !== 'anon') fail(`the configured key has role "${payload.role}". Only the anon/publishable key may be shipped to browsers.`);
    } catch { /* not a JWT we can read; allow */ }
  }
}
if (url && !/^https:\/\/[a-z0-9-]+(\.[a-z0-9-]+)+(:\d+)?$/i.test(url) && !/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(url)) fail(`SUPABASE_URL looks wrong: ${url}`);
if (appEnv === 'production' && (!url || !key)) fail('SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY must be set for production builds.');

const cfg = {
  supabaseUrl: url,
  supabaseKey: key,
  appEnv,
  recoveryCache: ['off', 'session', 'local'].includes(env.DSP_RECOVERY_CACHE) ? env.DSP_RECOVERY_CACHE : 'session',
  idleSignoutMinutes: env.DSP_IDLE_SIGNOUT_MINUTES !== undefined ? Number(env.DSP_IDLE_SIGNOUT_MINUTES) : 120,
  editIdleReleaseMinutes: env.DSP_EDIT_IDLE_RELEASE_MINUTES !== undefined ? Number(env.DSP_EDIT_IDLE_RELEASE_MINUTES) : 20,
};

// ---- CSP hash check for the inline print script written into the print iframe ----
const engine = readFileSync(join(src, 'js/form-engine.js'), 'utf8');
const hash = sha256(paginatorScript(engine));
const vercel = JSON.parse(readFileSync(join(root, 'vercel.json'), 'utf8'));
const csp = vercel.headers.flatMap((h) => h.headers).find((h) => h.key === 'Content-Security-Policy')?.value || '';
if (!csp.includes(hash)) fail(`vercel.json Content-Security-Policy must allow the print script hash ${hash} (form-engine.js print code changed?).`);

// ---- copy ------------------------------------------------------------------
if (!existsSync(join(src, 'vendor/supabase.js'))) fail('app/vendor/supabase.js missing. Run: npm run vendor');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(src, out, { recursive: true });
writeFileSync(join(out, 'config.js'),
  `/* generated by scripts/build.mjs — public configuration only */\nwindow.DSP_CONFIG=${JSON.stringify(cfg)};\n`);
console.log(`✔ built ${appEnv} → ${out}${url ? ` (Supabase ${new URL(url).host})` : ' (no Supabase configured)'}; recovery cache: ${cfg.recoveryCache}`);
